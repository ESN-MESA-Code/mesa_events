// `node scripts/gen-actions.mjs` – writes app/actions/<module>.ts, the
// "use server" exports of every action defined in lib/actions/<module>.ts
// (defineAction). Each export runs the action with the request's member and
// revalidates the pages. Run it after adding an action; the files are
// committed.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";

mkdirSync("app/actions", { recursive: true });
for (const file of readdirSync("lib/actions")) {
  if (!file.endsWith(".ts") || ["core.ts", "run.ts"].includes(file)) continue;
  const mod = file.replace(/\.ts$/, "");
  const src = readFileSync(`lib/actions/${file}`, "utf8");
  const names = [...src.matchAll(/^export const (\w+) = defineAction/gm)].map((m) => m[1]);
  if (!names.length) continue;
  const out = [
    '"use server";',
    "",
    `// Generated by scripts/gen-actions.mjs from lib/actions/${file} – do not edit.`,
    'import { revalidatePath } from "next/cache";',
    'import { run } from "@/lib/actions/run";',
    `import * as A from "@/lib/actions/${mod}";`,
    "",
    ...names.map(
      (n) => `export async function ${n}(input: unknown) {\n  const r = await run(A.${n}, input);\n  if (r.ok) revalidatePath("/", "layout");\n  return r;\n}\n`
    ),
  ];
  writeFileSync(`app/actions/${mod}.ts`, out.join("\n"));
  console.log(`app/actions/${mod}.ts: ${names.length} actions`);
}
