// `npm run gen:actions` – writes app/actions/<module>.ts, the "use server"
// exports of every action defined in lib/actions/<module>.ts
// (defineAction). Each export runs the action with the request's member;
// run() revalidates the pages the action declares. Run it after adding an
// action; the files are committed.
// `npm run gen:actions -- --check` fails if the committed files differ
// (CI, tests/unit/actions.test.ts).
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SKIP = ["core.ts", "run.ts"];

/** { "app/actions/<module>.ts": content } for every module with actions. */
export function generate(root = ".") {
  const out = {};
  for (const file of readdirSync(`${root}/lib/actions`).sort()) {
    if (!file.endsWith(".ts") || SKIP.includes(file)) continue;
    const mod = file.replace(/\.ts$/, "");
    const src = readFileSync(`${root}/lib/actions/${file}`, "utf8");
    const names = [...src.matchAll(/^export const (\w+) = defineAction/gm)].map((m) => m[1]);
    if (!names.length) continue;
    out[`app/actions/${mod}.ts`] = [
      '"use server";',
      "",
      `// Generated by scripts/gen-actions.mjs from lib/actions/${file} – do not edit.`,
      'import { run } from "@/lib/actions/run";',
      `import * as A from "@/lib/actions/${mod}";`,
      "",
      ...names.map((n) => `export async function ${n}(input: unknown) {\n  return run(A.${n}, input);\n}\n`),
    ].join("\n");
  }
  return out;
}

/** Files that are missing, differ, or should not exist. */
export function differences(root = ".") {
  const wanted = generate(root);
  const problems = [];
  for (const [path, content] of Object.entries(wanted)) {
    const file = `${root}/${path}`;
    if (!existsSync(file)) problems.push(`${path} is missing`);
    else if (readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== content) problems.push(`${path} is out of date`);
  }
  for (const file of readdirSync(`${root}/app/actions`)) {
    if (!(`app/actions/${file}` in wanted)) problems.push(`app/actions/${file} has no lib/actions module`);
  }
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    const problems = differences();
    if (problems.length) {
      console.error(`Generated actions are out of date – run \`npm run gen:actions\`:\n  ${problems.join("\n  ")}`);
      process.exit(1);
    }
    console.log("app/actions/* match lib/actions/*");
  } else {
    mkdirSync("app/actions", { recursive: true });
    for (const [path, content] of Object.entries(generate())) {
      writeFileSync(path, content);
      console.log(`${path}: ${(content.match(/^export async function/gm) ?? []).length} actions`);
    }
  }
}
